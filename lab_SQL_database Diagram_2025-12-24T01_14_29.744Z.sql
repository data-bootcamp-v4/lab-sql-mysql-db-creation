CREATE TABLE IF NOT EXISTS `Cars` (
	`id` INTEGER NOT NULL AUTO_INCREMENT UNIQUE,
	`vin` VARCHAR(1000) NOT NULL,
	`manufacturer` VARCHAR(1000) NOT NULL,
	`model` VARCHAR(1000) NOT NULL,
	`year` INTEGER NOT NULL,
	`colour` VARCHAR(255) NOT NULL,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Customers` (
	`id` INTEGER NOT NULL AUTO_INCREMENT UNIQUE,
	`cust_id` INTEGER NOT NULL,
	`cust_name` VARCHAR(255) NOT NULL,
	`cust_phone` VARCHAR(255) NOT NULL,
	`cust_email` VARCHAR(255) NOT NULL,
	`cust_address` VARCHAR(1000) NOT NULL,
	`cust_city` VARCHAR(255) NOT NULL,
	`cust_state` VARCHAR(255) NOT NULL,
	`cust_country` VARCHAR(255) NOT NULL,
	`cust_zipcode` INTEGER NOT NULL,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Salespersons` (
	`id` INTEGER NOT NULL AUTO_INCREMENT UNIQUE,
	`staff_id` VARCHAR(255) NOT NULL,
	`name` VARCHAR(255) NOT NULL,
	`store` VARCHAR(255) NOT NULL,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Invoices` (
	`id` INTEGER NOT NULL AUTO_INCREMENT UNIQUE,
	`invoice_number` VARCHAR(255),
	`date` DATE,
	`car` INTEGER,
	`customer` INTEGER,
	`salespersons` INTEGER,
	PRIMARY KEY(`id`)
);


ALTER TABLE `Invoices`
ADD FOREIGN KEY(`car`) REFERENCES `Cars`(`id`)
ON UPDATE NO ACTION ON DELETE NO ACTION;
ALTER TABLE `Salespersons`
ADD FOREIGN KEY(`id`) REFERENCES `Invoices`(`salespersons`)
ON UPDATE NO ACTION ON DELETE NO ACTION;
ALTER TABLE `Customers`
ADD FOREIGN KEY(`id`) REFERENCES `Invoices`(`customer`)
ON UPDATE NO ACTION ON DELETE NO ACTION;