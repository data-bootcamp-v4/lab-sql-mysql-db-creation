DROP TABLE IF EXISTS Invoices;

CREATE TABLE Invoices (id INT PRIMARY KEY AUTO_INCREMENT, Invoice_number INT UNSIGNED NOT NULL,	Date DATE,	Car CHAR(17), Customer INT UNSIGNED, Salesperson VARCHAR(50));


DROP TABLE IF EXISTS Salespersons;

CREATE TABLE Salespersons (Staff_ID CHAR(17), Name VARCHAR(50), Store VARCHAR(50));


DROP TABLE IF EXISTS Customers;

CREATE TABLE Customers (Customer_ID INT UNSIGNED PRIMARY KEY AUTO_INCREMENT, Name VARCHAR(100), Phone_number VARCHAR(25), E_mail VARCHAR(255) UNIQUE, Address VARCHAR(255), City VARCHAR(100), State_province VARCHAR(50), Country VARCHAR(50), Zip_postal_code VARCHAR(20));


DROP TABLE IF EXISTS cars;

CREATE TABLE cars (id INT UNSIGNED AUTO_INCREMENT, VIN CHAR(17) PRIMARY KEY, Manufacturer VARCHAR(100) , Year YEAR , Color VARCHAR(50), Model VARCHAR(100));
