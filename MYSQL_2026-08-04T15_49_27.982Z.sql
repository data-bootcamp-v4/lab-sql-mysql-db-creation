CREATE TABLE IF NOT EXISTS `Cars` (
	`VIN` BIGINT NOT NULL AUTO_INCREMENT UNIQUE,
	`Manufaturer` VARCHAR(255) NOT NULL,
	`Model` VARCHAR(255) NOT NULL,
	`Year` INT NOT NULL,
	`Color` VARCHAR(255),
	`Invoice_id` BIGINT NOT NULL,
	PRIMARY KEY(`VIN`)
);


CREATE TABLE IF NOT EXISTS `Customers` (
	`Customer_id` BIGINT NOT NULL AUTO_INCREMENT UNIQUE,
	`Name` VARCHAR(255),
	`Phone` BIGINT,
	`Address` VARCHAR(255),
	`email` VARCHAR(255),
	`city` VARCHAR(255),
	`state` VARCHAR(255),
	`country` VARCHAR(255),
	`zip code` BIGINT,
	PRIMARY KEY(`Customer_id`)
);


CREATE TABLE IF NOT EXISTS `Invoices` (
	`Invoice_id` BIGINT NOT NULL AUTO_INCREMENT UNIQUE,
	`Customer_id` BIGINT,
	`VIN` BIGINT,
	`Staff_id` BIGINT,
	`Date` DATETIME,
	PRIMARY KEY(`Invoice_id`)
);


CREATE TABLE IF NOT EXISTS `sales person` (
	`Staff_id` BIGINT NOT NULL AUTO_INCREMENT UNIQUE,
	`name` VARCHAR(255) NOT NULL,
	`Store` VARCHAR(255) NOT NULL,
	PRIMARY KEY(`Staff_id`)
);


