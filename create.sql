CREATE DATABASE IF NOT EXISTS lab_mysql;

USE lab_mysql;

CREATE TABLE IF NOT EXISTS `customers` (
	`id` INTEGER NOT NULL AUTO_INCREMENT UNIQUE,
	`cust_id` VARCHAR(120) NOT NULL,
	`cust_name` VARCHAR(120) NOT NULL,
	`cust_phone` VARCHAR(35),
	`cust_email` VARCHAR(120),
	`cust_address` VARCHAR(120) NOT NULL,
	`cust_city` VARCHAR(120) NOT NULL,
	`cust_state` VARCHAR(120) NOT NULL,
	`cust_country` VARCHAR(120) NOT NULL,
	`cust_zipcode` VARCHAR(35) NOT NULL,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `cars` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT UNIQUE,
	`vin` VARCHAR(120) NOT NULL,
	`manufacturer` VARCHAR(120) NOT NULL,
	`model` VARCHAR(120) NOT NULL,
	`year` SMALLINT NOT NULL,
	`color` VARCHAR(50),
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `salespersons` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT UNIQUE,
	`staff_id` VARCHAR(120) NOT NULL,
	`name` VARCHAR(120) NOT NULL,
	`store` VARCHAR(120) NOT NULL,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `invoices` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT UNIQUE,
	`invoice_number` VARCHAR(120) NOT NULL UNIQUE,
	`date` DATE NOT NULL,
	`car_id` INTEGER UNSIGNED NOT NULL,
	`customer_id` INTEGER NOT NULL,
	`salesperson_id` INTEGER UNSIGNED NOT NULL,
	PRIMARY KEY(`id`)
);


