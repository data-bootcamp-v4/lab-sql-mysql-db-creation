CREATE DATABASE IF NOT EXISTS lab_mysql;

USE lab_mysql;


DROP TABLE IF EXISTS `CARS`;
CREATE TABLE IF NOT EXISTS `CARS` (
	`car_id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`VIN` VARCHAR(255) NOT NULL,
	`Manufacturer` VARCHAR(255) NOT NULL,
	`Model` VARCHAR(255) NOT NULL,
	`Year` YEAR NOT NULL,
	`Color` VARCHAR(255) NOT NULL,
	PRIMARY KEY(`car_id`)
);

DROP TABLE IF EXISTS `CUSTOMERS`;
CREATE TABLE IF NOT EXISTS `CUSTOMERS` (
	`customer_ID` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`address_id` INTEGER NOT NULL,
	`name` VARCHAR(255),
	`email` VARCHAR(255),
	`phone` VARCHAR(255),
	PRIMARY KEY(`customer_ID`)
);

DROP TABLE IF EXISTS `INVOICES`;
CREATE TABLE IF NOT EXISTS `INVOICES` (
	`invoice_id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`invoice_nr` INTEGER NOT NULL UNIQUE,
	`car_id` INTEGER NOT NULL UNIQUE,
	`customer_id` INTEGER NOT NULL,
	`sp_id` INTEGER NOT NULL,
	`date` DATE NOT NULL,
	PRIMARY KEY(`invoice_id`)
);

DROP TABLE IF EXISTS `SALESPERSONS`;
CREATE TABLE IF NOT EXISTS `SALESPERSONS` (
	`sp_id` INTEGER NOT NULL AUTO_INCREMENT,
	`staff_id` INTEGER NOT NULL UNIQUE,
	`name` VARCHAR(255),
	`store` VARCHAR(255),
	PRIMARY KEY(`sp_id`)
);

DROP TABLE IF EXISTS `ADDRESS`;
CREATE TABLE IF NOT EXISTS `ADDRESS` (
	`address_id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`address` VARCHAR(255),
	`city` VARCHAR(255),
	`state` VARCHAR(255),
	`country` VARCHAR(255),
	`postal_code` VARCHAR(255),
	PRIMARY KEY(`address_id`)
);

ALTER TABLE `INVOICES`
ADD FOREIGN KEY (`car_id`) REFERENCES `CARS`(`car_id`)
ON UPDATE CASCADE ON DELETE CASCADE;

ALTER TABLE `INVOICES`
ADD FOREIGN KEY (`customer_id`) REFERENCES `CUSTOMERS`(`customer_ID`)
ON UPDATE NO ACTION ON DELETE NO ACTION;

ALTER TABLE `CUSTOMERS`
ADD FOREIGN KEY (`address_id`) REFERENCES `ADDRESS`(`address_id`)
ON UPDATE NO ACTION ON DELETE NO ACTION;

ALTER TABLE `INVOICES`
ADD FOREIGN KEY (`sp_id`) REFERENCES `SALESPERSONS`(`sp_id`)
ON UPDATE NO ACTION ON DELETE NO ACTION;