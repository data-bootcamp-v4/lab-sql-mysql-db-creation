CREATE DATABASE IF NOT EXISTS lab_mysql;
USE lab_mysql;
DROP TABLE IF EXISTS cars;
CREATE TABLE cars(
	`carID` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
	`VIN` VARCHAR(255) NOT NULL,
	`Manufacturer` VARCHAR(255) NOT NULL,
	`Model` VARCHAR(255) NOT NULL,
	`Year` INTEGER NOT NULL,
	`Color` VARCHAR(255) NOT NULL,
	PRIMARY KEY(`carID`)
);
DROP TABLE IF EXISTS Customers;
CREATE TABLE Customers(
	`CustomerID` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
	`Name` VARCHAR(255) NOT NULL,
	`Phone_Number` VARCHAR(255) NOT NULL,
	`Email` VARCHAR(255) NOT NULL,
	`Address` VARCHAR(255) NOT NULL,
	`City` VARCHAR(255) NOT NULL,
	`State_Province` VARCHAR(255) NOT NULL,
	`Country` VARCHAR(255) NOT NULL,
	`Zip_Code` INTEGER NOT NULL,
	PRIMARY KEY(`CustomerID`)
);

DROP TABLE IF EXISTS Sales_Persons;
CREATE TABLE IF NOT EXISTS Sales_Persons (
	`StaffID` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
	`Name` VARCHAR(255) NOT NULL,
	`Store` VARCHAR(255) NOT NULL,
	PRIMARY KEY(`StaffID`)
);

DROP TABLE IF EXISTS `Invoices`;
CREATE TABLE IF NOT EXISTS `Invoices` (
	`Invoice_Number` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
	`Date` DATE NOT NULL,
	`CustomerID` BIGINT NOT NULL,
	`CarID` BIGINT NOT NULL,
	`StaffID` BIGINT NOT NULL,
	PRIMARY KEY(`Invoice_Number`)
);
DROP TABLE IF EXISTS users;
CREATE TABLE IF NOT EXISTS users(
id BIGINT UNSIGNED NOT NULL,
name VARCHAR (30),
email VARCHAR (30), 
PRIMARY KEY(id)
);

